function createTypeDocConfiguration(packageName, label, config, pluginFactory) {
  const { entryPoints, tsconfig, ...typeDoc } = config;

  return pluginFactory({
    entryPoints,
    output: packageName,
    pagination: true,
    sidebar: {
      label,
      readmeLabel: "Overview",
    },
    tsconfig,
    typeDoc,
  });
}

function createAutogeneratedSidebarGroup(label, directory) {
  return {
    collapsed: true,
    items: [
      {
        autogenerate: {
          directory,
        },
      },
    ],
    label,
  };
}

function createIsaacScriptCommonSlug(directory, pageName) {
  return `isaacscript-common/${directory}/${pageName.toLowerCase()}`;
}
